namespace ChildeFood.Domain.Enums;

// وضعیت‌های مختلف سفارش رو مشخص می‌کنیم؛ از ثبت اولیه تا تحویل غذا به دانش‌آموز.
public enum OrderStatus
{
    Pending = 1,    // در انتظار پرداخت یا تایید
    Paid = 2,       // پرداخت شده و نهایی
    Preparing = 3,  // در حال آماده‌سازی و بسته‌بندی در آشپزخانه
    Delivered = 4,  // تحویل داده شده به دانش‌آموز در مدرسه
    Cancelled = 5   // لغو شده (چه توسط کاربر چه توسط سیستم)
}
